"""Phase 1, step 2: cold-start supervised fine-tuning on verified reasoning traces.

This is the "SFT round 1" box of the DeepSeek pipeline. The input is the JSONL produced
by ``rlm/distill.py``: problems from your domain with a teacher-generated reasoning trace
that *passed your verifier*. The output is a LoRA adapter that already speaks the
``<think>…</think><answer>…</answer>`` format before we ever run GRPO.

Run::

    uv run python -m rlm.train_sft --data rlm/data/sft_traces.jsonl --output rlm/weights/sft_lora

What is decided for you: the trainer (``trl.SFTTrainer``), LoRA, the conversational
format (``prompt`` + ``completion`` columns, so that the loss is computed only on the
assistant turn). What you decide: the data, the base model, epochs, learning rate,
sequence length. Write down in EXPERIMENTS.md why you chose them.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re

from datasets import load_dataset

from rlm.data import build_prompt, get_imv_rule_context
from rlm.imv_engine import evaluate_imv_case


def _trace_with_verified_components(trace: str, params: dict | None) -> str:
    """Supply oracle-verified intermediate targets as part of SFT supervision.

    Keep the teacher's original explanation, but prepend concise numeric
    targets so GRPO can later reward correct IMV/CAPI independently of the
    final total, even when a long generation never closes </think>.
    """
    if params is None:
        return trace  # Legacy traces without oracle inputs cannot be enriched.
    result = evaluate_imv_case(params)
    imv = f"{result['imv_monthly_eur']:.2f}"
    capi = f"{result['capi_monthly_eur']:.2f}"
    # A teacher in non-native-thinking mode may already emit these tags.
    # Never trust or preserve intermediate values generated by the teacher:
    # they could contradict the verified oracle despite a correct final sum.
    head, separator, tail = trace.partition("</think>")
    head = re.sub(r"<(?:imv|capi)>.*?</(?:imv|capi)>", "", head, flags=re.DOTALL)
    if not separator or re.search(r"</?(?:imv|capi)>", head):
        raise ValueError("Malformed teacher intermediate fields in SFT trace")
    head = head.replace(
        "<think>",
        f"<think>\n<imv>{imv}</imv> <capi>{capi}</capi>\n", 1,
    )
    return head + separator + tail


def select_verified_traces(dataset, max_per_problem: int):
    """Keep at most N short, distinct verified traces per question."""
    if max_per_problem <= 0:
        raise ValueError("max_per_problem must be positive")
    if "verified" in dataset.column_names:
        dataset = dataset.filter(lambda ex: bool(ex["verified"]))
    groups: dict[str, list[int]] = {}
    for idx, example in enumerate(dataset):
        groups.setdefault(example["question"], []).append(idx)
    selected = set()
    for indices in groups.values():
        ranked = sorted(indices, key=lambda i: (len(dataset[i]["trace"]), i))
        seen_traces: set[str] = set()
        for idx in ranked:
            trace = dataset[idx]["trace"]
            if trace in seen_traces:
                continue
            selected.add(idx)
            seen_traces.add(trace)
            if len(seen_traces) >= max_per_problem:
                break
    return dataset.select(sorted(selected))


def load_sft_dataset(path: str | Path, max_traces_per_problem: int = 2):
    """Turn distilled traces into TRL's prompt/completion conversational format.

    Expected JSONL fields: ``question``, ``trace`` (the full ``<think>…</think><answer>…</answer>``
    text) and ``answer``. Only traces marked ``verified: true`` are used.
    """
    dataset = load_dataset("json", data_files=str(path), split="train")
    dataset = select_verified_traces(dataset, max_traces_per_problem)
    return dataset.map(
        lambda ex: {
            "prompt": build_prompt(
                ex["question"],
                rule_context=ex.get("rule_context") or get_imv_rule_context(),
            ),
            "completion": [{
                "role": "assistant",
                "content": _trace_with_verified_components(ex["trace"], ex.get("params")),
            }],
        },
        remove_columns=dataset.column_names,
    )


def train(args: argparse.Namespace) -> None:
    import torch
    from peft import LoraConfig
    from transformers import AutoTokenizer
    from trl import SFTConfig, SFTTrainer

    from rlm.sft_preflight import validate_sft_sequences

    dataset = load_sft_dataset(args.data, args.max_traces_per_problem)
    print(f"{len(dataset)} verified traces loaded from {args.data}")
    if not len(dataset):
        raise ValueError("No verified traces: run distillation and validation before SFT.")

    tokenizer = AutoTokenizer.from_pretrained(args.model)
    report = validate_sft_sequences(
        dataset, tokenizer, args.max_length,
        args.validation_report or Path(args.output).parent / "sft_input_validation.json",
    )
    print(
        f"SFT preflight: {report['accepted']} complete tokenized sequences, "
        f"max {report['max_observed_tokens']}/{args.max_length} tokens",
        flush=True,
    )

    peft_config = LoraConfig(
        r=args.lora_rank,
        lora_alpha=2 * args.lora_rank,
        lora_dropout=0.05,
        target_modules="all-linear",
        task_type="CAUSAL_LM",
    )
    config = SFTConfig(
        output_dir=args.output,
        num_train_epochs=args.epochs,
        learning_rate=args.learning_rate,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=args.grad_accum,
        max_length=args.max_length,
        completion_only_loss=True,
        packing=False,
        bf16=torch.cuda.is_available(),
        gradient_checkpointing=True,
        logging_steps=10,
        save_strategy="steps",
        save_steps=args.save_steps,
        save_total_limit=3,
        report_to="none",
        model_init_kwargs={"dtype": torch.bfloat16 if torch.cuda.is_available() else torch.float32},
        # Completion-only loss uses the prompt/completion structure above.
    )
    trainer = SFTTrainer(
        model=args.model,
        args=config,
        train_dataset=dataset,
        peft_config=peft_config,
        processing_class=tokenizer,
    )
    trainer.train(resume_from_checkpoint=args.resume_from_checkpoint)
    trainer.save_model(args.output)
    print(f"adapter saved to {args.output}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--data", required=True, help="JSONL with question / trace / answer / verified"
    )
    parser.add_argument("--model", default="Qwen/Qwen3-0.6B")
    parser.add_argument("--output", default="rlm/weights/sft_lora")
    parser.add_argument("--epochs", type=float, default=2.0)
    parser.add_argument("--learning-rate", type=float, default=2e-4)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--grad-accum", type=int, default=4)
    parser.add_argument("--max-length", type=int, default=8192)
    parser.add_argument(
        "--max-traces-per-problem", type=int, default=2,
        help="maximum unique verified teacher traces used per problem in SFT",
    )
    parser.add_argument(
        "--validation-report", default=None,
        help="JSON report of the pre-training token and answer tag audit",
    )
    parser.add_argument("--lora-rank", type=int, default=16)
    parser.add_argument("--save-steps", type=int, default=50)
    parser.add_argument("--resume-from-checkpoint", default=None, help="checkpoint-XXX folder")
    train(parser.parse_args())


if __name__ == "__main__":
    main()
